/**
 * Photo binding.
 *
 * Every image on the site refers to a slot id, never a hard-coded path. A slot
 * resolves to `/photos/<id>.<ext>` once that file exists in `public/photos/`.
 * Until then the component renders a labelled placeholder naming the exact shot
 * and aspect it needs, so nothing silently ships as a grey box pretending to be
 * a photograph.
 *
 * To fill the site: drop the files into `public/photos/` using the ids below,
 * then run `python3 scripts/sync_photos.py` to regenerate MANIFEST.
 */

export interface Slot {
  /** Arabic label shown on the placeholder and used as the default alt text. */
  label: string;
  /** width / height the layout wants, so uploads can be cropped correctly. */
  ratio: number;
}

