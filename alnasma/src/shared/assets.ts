/**
 * Files present in public/photos, keyed by slot id. Regenerated by
 * scripts/sync_photos.py — an empty record means no photos uploaded yet.
 */
export const MANIFEST: Record<string, string> = {};

export function photoUrl(slot: string): string | null {
  return MANIFEST[slot] ?? null;
}

export function slotOf(id: string): Slot {
  return SLOTS[id] ?? { label: id, ratio: 1 };
}

/** How many slots are still waiting on a real file. */
export function missingSlots(): string[] {
  return Object.keys(SLOTS).filter((k) => !MANIFEST[k]);
}
